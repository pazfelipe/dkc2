"""Generate TypeScript symbol modules from the assembled DKC2 disassembly.

Inputs : the WLA symbol file produced by asar (labels, RAM names, struct fields, MMIO)
         and constants.asm (!defines).
Outputs: src/gen/rom_labels.json   ROM label -> 24-bit SNES address
         src/gen/ram.ts            WRAM variable addresses (R.*), struct field offsets, MMIO registers
         src/gen/constants.ts      numeric !defines (C.*)

Only names and addresses (facts) are exported; no ROM bytes.
"""
import json
import os
import re
import sys

SYM = sys.argv[1] if len(sys.argv) > 1 else "/home/claude/work/dkc2.sym"
CONST = sys.argv[2] if len(sys.argv) > 2 else "/home/claude/ref/dkc2dis/constants.asm"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "gen")
os.makedirs(OUT, exist_ok=True)

labels = {}
low = {}
sec = None
for line in open(SYM, encoding="latin-1"):
    line = line.strip()
    if line.startswith("["):
        sec = line
        continue
    if sec != "[labels]" or not line:
        continue
    m = re.match(r"([0-9A-Fa-f]{2}):([0-9A-Fa-f]{4}) (\S+)$", line)
    if not m:
        continue
    bank, addr, name = int(m.group(1), 16), int(m.group(2), 16), m.group(3)
    full = (bank << 16) | addr
    if name.startswith(":"):
        continue
    if bank >= 0x80:
        labels.setdefault(name, full)
    elif bank in (0x7E, 0x7F):
        low.setdefault(name, full)
    elif bank == 0:
        if name.startswith("APU_"):
            continue
        low.setdefault(name, full)

json.dump(labels, open(os.path.join(OUT, "rom_labels.json"), "w"), separators=(",", ":"))

# Split low (bank 00 / 7E / 7F) names into plain RAM vars and dotted groups
plain, groups = {}, {}
for name, v in low.items():
    if "." in name:
        head, rest = name.split(".", 1)
        head = head.replace("[", "_").replace("]", "")
        groups.setdefault(head, {})[rest.replace(".", "__").replace("[", "_").replace("]", "")] = v
    else:
        plain[name] = v


def ident(s):
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


lines = ["// Generated by tools/gen_symbols.py from the DKC2 disassembly. Do not edit.",
         "/* eslint-disable */", ""]
lines.append("/** WRAM variables and other bank $00/$7E/$7F names (addresses). */")
lines.append("export const R = {")
for k in sorted(plain):
    lines.append(f"  {ident(k)}: 0x{plain[k]:06X},")
lines.append("} as const;")
lines.append("")
for g in sorted(groups):
    lines.append(f"export const {ident(g)} = {{")
    base = low.get(g)
    if base is not None:
        lines.append(f"  _base: 0x{base:06X},")
    for k in sorted(groups[g]):
        lines.append(f"  {ident(k)}: 0x{groups[g][k]:06X},")
    lines.append("} as const;")
    lines.append("")
open(os.path.join(OUT, "ram.ts"), "w").write("\n".join(lines))

# constants
consts = {}
for line in open(CONST, encoding="latin-1"):
    m = re.match(r"\s*!(\w+)\s*=\s*\$([0-9A-Fa-f]+)\s*(;.*)?$", line)
    if m:
        consts[m.group(1)] = int(m.group(2), 16)
        continue
    m = re.match(r"\s*!(\w+)\s*=\s*(\d+)\s*(;.*)?$", line)
    if m:
        consts[m.group(1)] = int(m.group(2))
cl = ["// Generated by tools/gen_symbols.py from constants.asm. Do not edit.", "export const C = {"]
for k in sorted(consts):
    cl.append(f"  {ident(k)}: 0x{consts[k]:X},")
cl.append("} as const;")
open(os.path.join(OUT, "constants.ts"), "w").write("\n".join(cl) + "\n")
print("labels", len(labels), "ram", len(plain), "groups", len(groups), "consts", len(consts))
