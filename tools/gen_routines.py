"""Generate src/gen/routines.ts: one callable stub per code label of the original game.

Each stub dispatches to the TypeScript port when it has been registered, otherwise it runs the
ORIGINAL routine on the reference 65816 (hybrid mode). The entry context used for the fallback
(return kind, data bank, direct page, M/X flags) comes from:
  1. call traces of the original game (test/states/trace.json), when available
  2. static analysis of the routine body (RTS vs RTL)
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
src = open(os.path.join(HERE, "callgraph.py")).read().split("if __name__")[0]
exec(src)

TRACE = os.path.join(HERE, "..", "test", "states", "trace.json")
OUT = os.path.join(HERE, "..", "src", "gen", "routines.ts")

nodes, edges, addrs = parse()
trace = json.load(open(TRACE)) if os.path.exists(TRACE) else {}

# return kind per global label from its own body
ret_kind = {}
for name, d in nodes.items():
    if not d["code"]:
        continue
    lines = open(os.path.join(DIS, d["file"]), encoding="latin-1").read().split("\n")[d["start"] - 1:d["end"]]
    body = "\n".join(l.split(";", 1)[0] for l in lines)
    rts = len(re.findall(r"\bRTS\b", body))
    rtl = len(re.findall(r"\bRTL\b", body))
    ret_kind[name] = "jsl" if rtl > rts else ("jsr" if rts > 0 else None)

# static call style references
ref_style = {}
for f in sorted(os.listdir(DIS)):
    if not (f.startswith("bank_") and f.endswith(".asm")):
        continue
    for raw in open(os.path.join(DIS, f), encoding="latin-1"):
        line = raw.split(";", 1)[0]
        m = re.search(r"\b(JSL|JML|JSR|JMP)(\.[lw])?\s+([A-Za-z_][A-Za-z0-9_]*)", line)
        if m:
            k = "jsl" if m.group(1) in ("JSL", "JML") or m.group(2) == ".l" else "jsr"
            ref_style.setdefault(m.group(3), set()).add(k)

# sprite main routines return through sprite_return_address (JML [..]) -> ret mode 2
sprite_mains = set()
b3 = open(os.path.join(DIS, "bank_B3.asm"), encoding="latin-1").read()
tbl = b3[b3.index("sprite_main_table:"):]
for line in tbl.split("\n")[1:260]:
    m = re.match(r"\s*dw\s+([A-Za-z_][A-Za-z0-9_]*)", line)
    if m:
        sprite_mains.add(m.group(1))

code_banks = range(0x80, 0xC0)
stubs = []
names_seen = set()
for name, a in sorted(addrs.items(), key=lambda kv: kv[1]):
    bank = a >> 16
    if bank not in code_banks:
        continue
    if name.startswith("APU_") or name.startswith("DATA_"):
        continue
    parent = name
    is_code = name in nodes and nodes[name]["code"]
    if name not in nodes:
        # sublabel: find parent global label with longest prefix
        cands = [n for n in nodes if name.startswith(n + "_")]
        if not cands:
            continue
        parent = max(cands, key=len)
        is_code = nodes[parent]["code"]
    if not is_code:
        continue
    t = trace.get("%X" % a)
    kind = None
    db, dp, mx = bank, 0, 0
    if t:
        ks = t["kinds"]
        if "jsl" in ks:
            kind = "jsl"
        elif "jsr" in ks:
            kind = "jsr"
        db = int(max(t["db"].items(), key=lambda kv: kv[1])[0], 16)
        dp = int(max(t["dp"].items(), key=lambda kv: kv[1])[0], 16)
        p = max(t["p"].items(), key=lambda kv: kv[1])[0]
        mx = (1 if p.startswith("m8") else 0) | (2 if "x8" in p else 0)
    if kind is None:
        styles = ref_style.get(name, set())
        if len(styles) == 1:
            kind = next(iter(styles))
        else:
            kind = ret_kind.get(parent) or "jsl"
    body = ret_kind.get(name) if name in nodes else None
    if name in sprite_mains:
        ret = 2
    elif body == "jsl":
        ret = 1
    elif body == "jsr":
        ret = 0
    else:
        ret = 1 if kind == "jsl" else 0
    ident = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if ident in names_seen:
        continue
    names_seen.add(ident)
    stubs.append((ident, a, kind, db, dp, mx, ret))

with open(OUT, "w") as f:
    f.write("// Generated by tools/gen_routines.py. Do not edit.\n")
    f.write("// One stub per routine label of the original game. Calling a stub runs the TypeScript port\n")
    f.write("// when registered, otherwise the original routine on the reference CPU (hybrid mode).\n")
    f.write("/* eslint-disable */\n")
    f.write('import { stub } from "../core/hybrid";\n\n')
    for ident, a, kind, db, dp, mx, ret in stubs:
        f.write(f"export const {ident} = stub(0x{a:06X}, {1 if kind == 'jsl' else 0}, 0x{db:02X}, 0x{dp:X}, {mx}, {ret});\n")
print("stubs", len(stubs))
